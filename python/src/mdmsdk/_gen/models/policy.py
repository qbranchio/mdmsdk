T = TypeVar("T", bound="Policy")



@_attrs_define
class Policy:
    """ Settings: items from the catalog (GET /api/v1/catalog). Items a device's level or OS cannot take are left out of its
    declarations and reported unsupported. Secret keys (marked in the catalog) are write-only: responses show {"secret":
    "set"}; a PUT that sends it keeps the stored value, a string replaces it, and leaving the key out clears it.

        Attributes:
            items (list[PolicyItem]):
     """

    items: list[PolicyItem]
    additional_properties: dict[str, Any] = _attrs_field(init=False, factory=dict)





    def to_dict(self) -> dict[str, Any]:
        from ..models.policy_item import PolicyItem # noqa: PLC0415
        items = []
        for items_item_data in self.items:
            items_item = items_item_data.to_dict()
            items.append(items_item)




        field_dict: dict[str, Any] = {}
        field_dict.update(self.additional_properties)
        field_dict.update({
            "items": items,
        })

        return field_dict



    @classmethod
    def from_dict(cls: type[T], src_dict: Mapping[str, Any]) -> T:
        from ..models.policy_item import PolicyItem # noqa: PLC0415
        d = dict(src_dict)
        items = []
        _items = d.pop("items")
        for items_item_data in (_items):
            items_item = PolicyItem.from_dict(items_item_data)



            items.append(items_item)


        policy = cls(
            items=items,
        )


        policy.additional_properties = d
        return policy

    @property
    def additional_keys(self) -> list[str]:
        return list(self.additional_properties.keys())

    def __getitem__(self, key: str) -> Any:
        return self.additional_properties[key]

    def __setitem__(self, key: str, value: Any) -> None:
        self.additional_properties[key] = value

    def __delitem__(self, key: str) -> None:
        del self.additional_properties[key]

    def __contains__(self, key: str) -> bool:
        return key in self.additional_properties
