"""Writes src/mdmsdk/_services.py: one method per methods.yaml entry over the
generated client in mdmsdk._gen, with the operation's retry and idempotency
facts from the contract. Run after regenerating _gen."""

from __future__ import annotations

import importlib
import inspect
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "src"))

SKIP = {"client", "mdm_actor", "idempotency_key"}


def snake(name: str) -> str:
    # The generator's own rule, so module names match what it wrote.
    from openapi_python_client.strings import snake_case

    return snake_case(name)


def result_type(annotation: str) -> str:
    """Response[X | Problem] -> X; an operation with no body -> None."""
    annotation = re.sub(r"(?:[\w]+\.)+(\w+)", r"\1", annotation)
    inner = annotation.removeprefix("Response[").removesuffix("]")
    parts = [p.strip() for p in inner.split("|") if p.strip() not in ("Problem", "Any", "")]
    return " | ".join(parts) if parts else "None"


def paged(contract: dict, op: dict) -> tuple[str, str] | None:
    """A cursor-paged list: a query parameter cursor, and a response object of
    next_cursor and one array. Returns the array's field and item model."""
    if not any(p.get("in") == "query" and p.get("name") == "cursor" for p in op.get("parameters", [])):
        return None
    ok = next((v for k, v in op["responses"].items() if k.startswith("2")), {})
    ref = ok.get("content", {}).get("application/json", {}).get("schema", {}).get("$ref", "")
    props = contract["components"]["schemas"].get(ref.rsplit("/", 1)[-1], {}).get("properties", {})
    if "next_cursor" not in props or len(props) != 2:
        return None
    field, schema = next((k, v) for k, v in props.items() if k != "next_cursor")
    if schema.get("type") != "array" or "$ref" not in schema.get("items", {}):
        return None
    return snake(field), schema["items"]["$ref"].rsplit("/", 1)[-1]


def main() -> None:
    # Importing the generated modules imports mdmsdk, which imports
    # _services: start from a stub so a broken previous output cannot block.
    (ROOT / "src" / "mdmsdk" / "_services.py").write_text("SERVICES: dict[str, type] = {}\n")
    contract = yaml.safe_load((ROOT.parent / "openapi" / "openapi.yaml").read_text())
    methods = yaml.safe_load((ROOT.parent / "methods.yaml").read_text())
    ops: dict[str, tuple[str, dict]] = {}
    for item in contract["paths"].values():
        for verb, op in item.items():
            if verb != "parameters":
                ops[op["operationId"]] = (verb.upper(), op)
    by_service: dict[str, list[str]] = {}
    for op_id, m in sorted(methods.items()):
        by_service.setdefault(m["service"], []).append(op_id)

    out = ['"""Generated by gen.py from methods.yaml and openapi/openapi.yaml. Do not edit."""', "",
           "# pyright: reportUnusedImport=false", "from __future__ import annotations", "",
           "import datetime", "import uuid", "from collections.abc import AsyncIterator, Iterator", "from typing import Any", "", "from ._call import call, call_async", "from ._gen.models import *",
           "from ._gen.types import UNSET, Unset", "from ._transport import OpInfo", ""]
    for service in sorted(by_service):
        cls = "".join(p.capitalize() for p in service.split("_")) + "Service"
        out += ["", f"class {cls}:", f'    """The {service} resource."""', "",
                "    def __init__(self, client: Any) -> None:", "        self._c = client", ""]
        for op_id in by_service[service]:
            method_name, op = snake(methods[op_id]["method"]), ops[op_id][1]
            tag = (op.get("tags") or ["default"])[0]
            module = f"._gen.api.{snake(tag)}.{snake(op_id)}"
            mod = importlib.import_module(module, package="mdmsdk")
            sig = inspect.signature(mod.sync_detailed)
            params = [p for p in sig.parameters.values() if p.name not in SKIP]
            pos = [p for p in params if p.default is inspect.Parameter.empty]
            kw = [p for p in params if p.default is not inspect.Parameter.empty]
            def ann(p: inspect.Parameter) -> str:
                return inspect.formatannotation(p.annotation)

            decl = ", ".join([f"{p.name}: {ann(p)}" for p in pos])
            if kw:
                decl = (decl + ", " if decl else "") + "*, " + ", ".join(f"{p.name}: {ann(p)} = UNSET" for p in kw)
            args = ", ".join(f"{p.name}={p.name}" for p in params)
            idem = any(p.get("name") == "Idempotency-Key" for p in op.get("parameters", []))
            info = f'OpInfo("{op_id}", idempotent={idem}, retry_transport={op_id == "createToken"}, read={bool(methods[op_id].get("read"))})'
            summary = op.get("summary", "")
            ret = result_type(inspect.formatannotation(sig.return_annotation))
            call_kwargs = "{" + ", ".join(repr(p.name) + ": " + p.name for p in params) + "}"
            head = f"self{', ' + decl if decl else ''}"
            page = paged(contract, op)
            if page is not None:
                # A cursor-paged list iterates every page; the caller never
                # handles the cursor.
                field, item = page
                out += [f"    def {method_name}({head}) -> Iterator[{item}]:",
                        f'        """{summary} ({op_id}), every page."""',
                        "        while True:",
                        f'            page = call(self._c, "{module}", {info}, {call_kwargs})',
                        f"            yield from page.{field}",
                        "            if not page.next_cursor:",
                        "                return",
                        "            cursor = page.next_cursor", ""]
                out += [f"    async def {method_name}_async({head}) -> AsyncIterator[{item}]:",
                        f'        """{summary} ({op_id}), every page, async."""',
                        "        while True:",
                        f'            page = await call_async(self._c, "{module}", {info}, {call_kwargs})',
                        f"            for item in page.{field}:",
                        "                yield item",
                        "            if not page.next_cursor:",
                        "                return",
                        "            cursor = page.next_cursor", ""]
            elif ret.startswith("list["):
                # Lists are iterators, so paging can arrive without breaking callers.
                item = ret.removeprefix("list[").removesuffix("]")
                out += [f"    def {method_name}({head}) -> Iterator[{item}]:",
                        f'        """{summary} ({op_id})."""',
                        f'        yield from call(self._c, "{module}", {info}, {call_kwargs})', ""]
                out += [f"    async def {method_name}_async({head}) -> AsyncIterator[{item}]:",
                        f'        """{summary} ({op_id}), async."""',
                        f'        for item in await call_async(self._c, "{module}", {info}, {call_kwargs}):',
                        "            yield item", ""]
            else:
                out += [f"    def {method_name}({head}) -> {ret}:",
                        f'        """{summary} ({op_id})."""',
                        f'        return call(self._c, "{module}", {info}, {call_kwargs})', ""]
                out += [f"    async def {method_name}_async({head}) -> {ret}:",
                        f'        """{summary} ({op_id}), async."""',
                        f'        return await call_async(self._c, "{module}", {info}, {call_kwargs})', ""]
            _ = args
    out += ["", "SERVICES = {"] + [f'    "{s}": {"".join(p.capitalize() for p in s.split("_"))}Service,' for s in sorted(by_service)] + ["}", ""]
    text = "\n".join(out)
    # Import only the standard modules the annotations use.
    for mod in ("datetime", "uuid"):
        if f"{mod}." not in text.split("from ._transport import OpInfo", 1)[1]:
            text = text.replace(f"import {mod}\n", "", 1)
    # Annotations come from inspect fully qualified; the module imports the names.
    text = re.sub(r"mdmsdk\._gen\.(?:\w+\.)*(\w+)", r"\1", text)
    (ROOT / "src" / "mdmsdk" / "_services.py").write_text(text)


if __name__ == "__main__":
    main()
