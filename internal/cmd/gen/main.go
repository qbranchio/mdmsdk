// Command gen writes services_gen.go: one method per methods.yaml entry,
// over the low-level client in package api, with the operation's retry and
// idempotency facts from the contract.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
	"unicode"

	"gopkg.in/yaml.v3"
)

type method struct {
	Service string `yaml:"service"`
	Method  string `yaml:"method"`
}

type param struct {
	Name   string         `yaml:"name"`
	In     string         `yaml:"in"`
	Schema map[string]any `yaml:"schema"`
}

type operation struct {
	ID          string              `yaml:"operationId"`
	Summary     string              `yaml:"summary"`
	Parameters  []param             `yaml:"parameters"`
	RequestBody map[string]any      `yaml:"requestBody"`
	Responses   map[string]response `yaml:"responses"`
}

type response struct {
	Content map[string]struct {
		Schema map[string]any `yaml:"schema"`
	} `yaml:"content"`
}

func main() {
	var doc struct {
		Paths map[string]map[string]yaml.Node `yaml:"paths"`
	}
	load("openapi/openapi.yaml", &doc)
	var methods map[string]method
	load("methods.yaml", &methods)

	type found struct {
		path string
		op   operation
	}
	ops := map[string]found{}
	for path, item := range doc.Paths {
		for verb, node := range item {
			if verb == "parameters" {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				log.Fatal(err)
			}
			ops[op.ID] = found{path, op}
		}
	}

	services := map[string][]string{}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/cmd/gen from methods.yaml and openapi/openapi.yaml. DO NOT EDIT.\n\npackage mdmsdk\n\n")
	fmt.Fprintf(&b, "import (\n\t\"context\"\n\t\"iter\"\n\n\topenapi_types \"github.com/oapi-codegen/runtime/types\"\n\n\t\"github.com/qbranchio/mdmsdk/api\"\n)\n\nvar (\n\t_ openapi_types.UUID\n\t_ iter.Seq[int]\n)\n\n")
	ids := make([]string, 0, len(methods))
	for id := range methods {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		m := methods[id]
		f, ok := ops[id]
		if !ok {
			log.Fatalf("methods.yaml: %s is not in the contract", id)
		}
		services[m.Service] = append(services[m.Service], id)
		emit(&b, m, f.path, f.op)
	}
	names := make([]string, 0, len(services))
	for s := range services {
		names = append(names, s)
	}
	sort.Strings(names)
	fmt.Fprintf(&b, "// services are the API's resources, as fields of Client.\ntype services struct {\n")
	for _, s := range names {
		fmt.Fprintf(&b, "\t%s *%sService\n", exported(s), exported(s))
	}
	fmt.Fprintf(&b, "}\n\nfunc newServices(c *Client) services {\n\treturn services{\n")
	for _, s := range names {
		fmt.Fprintf(&b, "\t\t%s: &%sService{c: c},\n", exported(s), exported(s))
	}
	fmt.Fprintf(&b, "\t}\n}\n")
	for _, s := range names {
		fmt.Fprintf(&b, "\n// %sService is the %s resource.\ntype %sService struct{ c *Client }\n", exported(s), s, exported(s))
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("%v\n%s", err, b.String())
	}
	if err := os.WriteFile("services_gen.go", out, 0o600); err != nil {
		log.Fatal(err)
	}
}

func emit(b *bytes.Buffer, m method, path string, op operation) {
	goOp := exported(op.ID)
	var args, call []string
	for _, seg := range strings.Split(path, "/") {
		if !strings.HasPrefix(seg, "{") {
			continue
		}
		name := strings.Trim(seg, "{}")
		typ := "string"
		for _, p := range op.Parameters {
			if p.In == "path" && p.Name == name && p.Schema["format"] == "uuid" {
				typ = "openapi_types.UUID"
			}
		}
		args = append(args, lowerIdent(name)+" "+typ)
		call = append(call, lowerIdent(name))
	}
	hasQuery, hasParams, idempotent := false, false, false
	for _, p := range op.Parameters {
		switch p.In {
		case "query":
			hasQuery, hasParams = true, true
		case "header":
			hasParams = true
			if p.Name == "Idempotency-Key" {
				idempotent = true
			}
		}
	}
	if hasQuery {
		args = append(args, "params *api."+goOp+"Params")
		call = append(call, "orEmpty(params)")
	} else if hasParams {
		call = append(call, "&api."+goOp+"Params{}")
	}
	if op.RequestBody != nil {
		args = append(args, "body api."+goOp+"JSONRequestBody")
		call = append(call, "body")
	}
	status, result := success(op)
	sig := strings.Join(append([]string{"ctx context.Context"}, args...), ", ")
	opInfo := fmt.Sprintf("opInfo{id: %q, idempotent: %v, retryTransport: %v}", op.ID, idempotent, op.ID == "createToken")
	callArgs := strings.Join(append([]string{"withOp(ctx, " + opInfo + ")"}, call...), ", ")
	fmt.Fprintf(b, "// %s: %s (%s).\n", exported(m.Method), op.Summary, op.ID)
	if result == "" {
		fmt.Fprintf(b, "func (s *%sService) %s(%s) error {\n", exported(m.Service), exported(m.Method), sig)
		fmt.Fprintf(b, "\tresp, err := s.c.low.%sWithResponse(%s)\n\tif err != nil {\n\t\treturn err\n\t}\n", goOp, callArgs)
		fmt.Fprintf(b, "\tif resp.StatusCode() == %s {\n\t\treturn nil\n\t}\n\treturn decodeError(resp.HTTPResponse, resp.Body)\n}\n\n", status)
		return
	}
	if strings.HasPrefix(result, "*[]") {
		// Lists are iterators, so paging can arrive without breaking callers.
		item := strings.TrimPrefix(result, "*[]")
		fmt.Fprintf(b, "func (s *%sService) %s(%s) iter.Seq2[%s, error] {\n", exported(m.Service), exported(m.Method), sig, item)
		fmt.Fprintf(b, "\treturn func(yield func(%s, error) bool) {\n", item)
		fmt.Fprintf(b, "\t\tresp, err := s.c.low.%sWithResponse(%s)\n", goOp, callArgs)
		fmt.Fprintf(b, "\t\tif err == nil && resp.JSON%s == nil {\n\t\t\terr = decodeError(resp.HTTPResponse, resp.Body)\n\t\t}\n", status)
		fmt.Fprintf(b, "\t\tif err != nil {\n\t\t\tvar zero %s\n\t\t\tyield(zero, err)\n\t\t\treturn\n\t\t}\n", item)
		fmt.Fprintf(b, "\t\tfor _, v := range *resp.JSON%s {\n\t\t\tif !yield(v, nil) {\n\t\t\t\treturn\n\t\t\t}\n\t\t}\n\t}\n}\n\n", status)
		return
	}
	fmt.Fprintf(b, "func (s *%sService) %s(%s) (%s, error) {\n", exported(m.Service), exported(m.Method), sig, result)
	fmt.Fprintf(b, "\tresp, err := s.c.low.%sWithResponse(%s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", goOp, callArgs)
	fmt.Fprintf(b, "\tif resp.JSON%s != nil {\n\t\treturn resp.JSON%s, nil\n\t}\n\treturn nil, decodeError(resp.HTTPResponse, resp.Body)\n}\n\n", status, status)
}

// success is the first 2xx status and its Go result type ("" for no body).
func success(op operation) (string, string) {
	codes := make([]string, 0, len(op.Responses))
	for code := range op.Responses {
		if strings.HasPrefix(code, "2") {
			codes = append(codes, code)
		}
	}
	sort.Strings(codes)
	if len(codes) == 0 {
		log.Fatalf("%s: no success response", op.ID)
	}
	code := codes[0]
	content, ok := op.Responses[code].Content["application/json"]
	if !ok {
		return code, ""
	}
	return code, "*" + goType(content.Schema)
}

func goType(s map[string]any) string {
	if ref, ok := s["$ref"].(string); ok {
		return "api." + ref[strings.LastIndex(ref, "/")+1:]
	}
	if s["type"] == "array" {
		items, _ := s["items"].(map[string]any)
		return "[]" + goType(items)
	}
	log.Fatalf("unsupported response schema %v", s)
	return ""
}

func exported(s string) string {
	var out []rune
	up := true
	for _, r := range s {
		if r == '_' || r == '-' {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		out = append(out, r)
	}
	return string(out)
}

func lowerIdent(s string) string {
	e := exported(s)
	return strings.ToLower(e[:1]) + e[1:]
}

func load(path string, v any) {
	raw, err := os.ReadFile(path) // #nosec G304 -- the generator's own inputs
	if err != nil {
		log.Fatal(err)
	}
	if err := yaml.Unmarshal(raw, v); err != nil {
		log.Fatalf("%s: %v", path, err)
	}
}
